import Foundation
import BCUShared

/// Everything an agent is told: the MCP server instructions, each tool's
/// description and parameters, and the skill.
enum AgentDocs {
    static let skillName = "background-computer-use"

    /// The skill shipped in the app bundle, or the repo copy when run from a checkout.
    static func skillFile() -> URL? {
        let exe = URL(fileURLWithPath: CommandLine.arguments[0]).resolvingSymlinksInPath()
        let candidates = [
            exe.deletingLastPathComponent().deletingLastPathComponent()
                .appendingPathComponent("Resources/skills/\(skillName)/SKILL.md"),
            URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
                .appendingPathComponent("skills/\(skillName)/SKILL.md"),
        ]
        return candidates.first { FileManager.default.fileExists(atPath: $0.path) }
    }

    static func markdown(skill: URL?) -> String {
        var out: [String] = []
        out.append("# What agents are told")
        out.append("")
        out.append("This is generated by `bcu docs`. An agent connected to `bcu mcp` gets the server instructions when it connects and the tool list right after. The skill is loaded only by agents that have it installed (`bcu install-skill`) and only when a task calls for it.")
        out.append("")
        out.append("## Server instructions")
        out.append("")
        out.append("Sent in the MCP `initialize` reply.")
        out.append("")
        out.append("```")
        out.append(ToolCatalog.serverInstructions)
        out.append("```")
        out.append("")
        out.append("## Tools")
        out.append("")
        for tool in ToolCatalog.tools {
            let name = tool["name"] as? String ?? ""
            out.append("### \(name)")
            out.append("")
            out.append(tool["description"] as? String ?? "")
            let schema = tool["inputSchema"] as? JSONObject ?? [:]
            let props = schema["properties"] as? JSONObject ?? [:]
            let required = Set(schema["required"] as? [String] ?? [])
            if !props.isEmpty {
                out.append("")
                for key in orderedKeys(props, required: required) {
                    let p = props[key] as? JSONObject ?? [:]
                    var type = p["type"] as? String ?? "any"
                    if type == "array", let items = p["items"] as? JSONObject, let t = items["type"] as? String {
                        type = "array of \(t)"
                    }
                    let flag = required.contains(key) ? ", required" : ""
                    let desc = (p["description"] as? String).map { $0.isEmpty ? "" : ": \($0)" } ?? ""
                    out.append("- `\(key)` (\(type)\(flag))\(desc)")
                }
            }
            out.append("")
        }
        out.append("## Skill")
        out.append("")
        if let skill, let text = try? String(contentsOf: skill, encoding: .utf8) {
            out.append("`skills/\(skillName)/SKILL.md`. Agents see the `description` line up front and read the rest when they use the skill.")
            out.append("")
            out.append(demoteHeadings(text))
        } else {
            out.append("No skill file found next to this `bcu`.")
        }
        return out.joined(separator: "\n")
    }

    /// Copy the skill into Claude Code's and Codex's user skill folders.
    static func installSkill() throws -> [String] {
        guard let source = skillFile()?.deletingLastPathComponent() else {
            throw NSError(domain: "bcu", code: 1, userInfo: [NSLocalizedDescriptionKey: "can't find the skill next to this bcu"])
        }
        let home = FileManager.default.homeDirectoryForCurrentUser
        var installed: [String] = []
        for root in [".claude/skills", ".codex/skills"] {
            let dest = home.appendingPathComponent(root).appendingPathComponent(skillName)
            try FileManager.default.createDirectory(at: dest.deletingLastPathComponent(), withIntermediateDirectories: true)
            if FileManager.default.fileExists(atPath: dest.path) { try FileManager.default.removeItem(at: dest) }
            try FileManager.default.copyItem(at: source, to: dest)
            installed.append(dest.path)
        }
        return installed
    }

    /// Required parameters first, then the rest, each group alphabetical.
    private static func orderedKeys(_ props: JSONObject, required: Set<String>) -> [String] {
        let keys = props.keys.sorted()
        return keys.filter { required.contains($0) } + keys.filter { !required.contains($0) }
    }

    /// Push the skill's headings one level down so they nest under "## Skill".
    private static func demoteHeadings(_ text: String) -> String {
        var inFence = false
        return text.split(separator: "\n", omittingEmptySubsequences: false).map { line in
            if line.hasPrefix("```") { inFence.toggle() }
            return !inFence && line.hasPrefix("#") ? "##" + line : String(line)
        }.joined(separator: "\n")
    }
}
